/**
 * Type-checks a namespace import and a default import of every typed entry of every `@sentry/*` package, with
 * several TypeScript versions and module settings.
 *
 * The expected result of a default import comes from the JS file that the runtime loads:
 * - ESM file: TypeScript must report an error, unless the entry has a real default export.
 * - CJS file: the default import is `module.exports`, or the real default export where the runtime reads
 *   `__esModule` (TypeScript's `esModuleInterop` and bundlers, but not Node's `import`).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { APP_DIR, getPackageJson, getPackageNames, getTypedEntries } from './entries.mjs';

const GENERATED_DIR = path.join(APP_DIR, 'generated');

const COMPILER_OPTIONS = {
  strict: true,
  noEmit: true,
  skipLibCheck: true,
  target: 'es2022',
  lib: ['es2022', 'dom'],
  types: ['node'],
};

const CONFIGS = {
  nodenext: { compilerOptions: { module: 'nodenext', moduleResolution: 'nodenext' }, files: ['esm.mts', 'cjs.cts'] },
  bundler: { compilerOptions: { module: 'esnext', moduleResolution: 'bundler' }, files: ['bundler.ts'] },
  // TypeScript reports a missing default export of an ESM file in bundler mode only since 5.6.
  'bundler-no-default': {
    compilerOptions: { module: 'esnext', moduleResolution: 'bundler' },
    files: ['bundler-no-default.ts'],
  },
  // The setup of https://github.com/getsentry/sentry-javascript/issues/3105. TypeScript 7 removed `node10`.
  node10: {
    compilerOptions: { module: 'commonjs', moduleResolution: 'node10', esModuleInterop: true },
    files: ['node10.ts'],
  },
};

const TYPESCRIPT_VERSIONS = {
  // The lowest version that the SDK supports.
  'typescript-5.0': { configs: ['nodenext', 'bundler', 'node10'] },
  'typescript-5.9': { configs: ['nodenext', 'bundler', 'bundler-no-default', 'node10'] },
  'typescript-6.0': {
    configs: ['nodenext', 'bundler', 'bundler-no-default', 'node10'],
    args: ['--ignoreDeprecations', '6.0'],
  },
  'typescript-7.0': { configs: ['nodenext', 'bundler', 'bundler-no-default'] },
};

// A type from a dependency that the app does not install (for example a framework) is `any`, so both checks accept it.
const HEADER = `// Generated by scripts/check-types.mjs.
type IsAny<T> = 0 extends 1 & T ? true : false;
/** \`true\` if the default import has all named exports, like \`module.exports\` of a CJS module. */
type IsWholeModule<Default, Namespace> =
  IsAny<Default> extends true ? true : [Exclude<keyof Namespace, 'default'>] extends [keyof Default] ? true : false;
/** \`true\` if the default import has a \`default\` property, like \`module.exports\` of a CJS module with a default export. */
type HasDefaultProperty<Default> = IsAny<Default> extends true ? false : 'default' extends keyof Default ? true : false;
`;

/** Returns the code that imports an entry and checks what its default import is. */
function importCode(entry, index, defaultImport) {
  const ns = `ns${index}`;
  const def = `default${index}`;
  const lines = [`import * as ${ns} from '${entry.specifier}';`];

  if (defaultImport === 'error') {
    lines.push(
      '// @ts-expect-error -- The ESM build has no default export.',
      `import ${def} from '${entry.specifier}';`,
    );
  } else if (defaultImport === 'module') {
    lines.push(
      `import ${def} from '${entry.specifier}';`,
      `const check${index}: IsWholeModule<typeof ${def}, typeof ${ns}> = true;`,
    );
  } else if (defaultImport === 'real') {
    lines.push(
      `import ${def} from '${entry.specifier}';`,
      `const check${index}: HasDefaultProperty<typeof ${def}> = false;`,
    );
  }

  return lines.join('\n');
}

/**
 * What a default import gives for a JS file of `format`: `error`, `module` (`module.exports`) or `real` (the
 * default export). `readsEsModule` is true where the import reads the `__esModule` marker of a CJS file.
 */
function defaultImportOf(entry, format, readsEsModule) {
  if (format === 'esm') {
    return entry.hasDefaultExport ? 'real' : 'error';
  }
  return entry.hasDefaultExport && readsEsModule ? 'real' : 'module';
}

const entries = getPackageNames().flatMap(name => getTypedEntries(name));
const files = { 'esm.mts': [], 'cjs.cts': [], 'bundler.ts': [], 'bundler-no-default.ts': [], 'node10.ts': [] };

entries.forEach((entry, index) => {
  const { nodeImport, nodeRequire, bundler } = entry.formats;

  if (nodeImport) {
    files['esm.mts'].push(importCode(entry, index, defaultImportOf(entry, nodeImport, false)));
  }
  if (nodeRequire === 'cjs') {
    files['cjs.cts'].push(importCode(entry, index, defaultImportOf(entry, nodeRequire, true)));
    // `node10` ignores `exports` and reads only the `types` field.
    if (entry.subpath === '.' && getPackageJson(entry.packageName).types) {
      files['node10.ts'].push(importCode(entry, index, defaultImportOf(entry, nodeRequire, true)));
    }
  }
  if (bundler) {
    const defaultImport = defaultImportOf(entry, bundler, true);
    files['bundler.ts'].push(importCode(entry, index, defaultImport === 'error' ? 'none' : defaultImport));
    if (defaultImport === 'error') {
      files['bundler-no-default.ts'].push(importCode(entry, index, 'error'));
    }
  }
});

fs.rmSync(GENERATED_DIR, { recursive: true, force: true });
fs.mkdirSync(GENERATED_DIR);
for (const [file, blocks] of Object.entries(files)) {
  fs.writeFileSync(path.join(GENERATED_DIR, file), `${HEADER}\n${blocks.join('\n\n')}\n\nexport {};\n`);
}
for (const [name, { compilerOptions, files: configFiles }] of Object.entries(CONFIGS)) {
  const tsconfig = { compilerOptions: { ...COMPILER_OPTIONS, ...compilerOptions }, files: configFiles };
  fs.writeFileSync(path.join(GENERATED_DIR, `tsconfig.${name}.json`), `${JSON.stringify(tsconfig, null, 2)}\n`);
}

const failed = [];
for (const [typescript, { configs, args = [] }] of Object.entries(TYPESCRIPT_VERSIONS)) {
  const tsc = path.join(APP_DIR, 'node_modules', typescript, 'bin', 'tsc');
  for (const config of configs) {
    const label = `${typescript} ${config}`;
    try {
      execFileSync(process.execPath, [tsc, '-p', path.join(GENERATED_DIR, `tsconfig.${config}.json`), ...args], {
        stdio: 'inherit',
      });
      console.log(`${label}: ok`);
    } catch {
      console.error(`${label}: failed`);
      failed.push(label);
    }
  }
}

if (failed.length) {
  console.error(`\nType checks failed: ${failed.join(', ')}`);
  process.exit(1);
}

console.log(`\nTypes: ${entries.length} entries, all type checks passed.`);
